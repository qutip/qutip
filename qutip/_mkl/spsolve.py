def _default_solver_args():
    return {
        'hermitian': False,
        'posdef': False,
        'max_iter_refine': 10,
        'scaling_vectors': True,
        'weighted_matching': True,
        'return_info': False,
    }


class mkl_lu:
    """
    Object pointing to LU factorization of a sparse matrix
    generated by mkl_splu.

    Methods
    -------
    solve(b, verbose=False)
        Solve system of equations using given RHS vector 'b'.
        Returns solution ndarray with same shape as input.

    info()
        Returns the statistics of the factorization and
        solution in the lu.info attribute.

    delete()
        Deletes the allocated solver memory.

    """
    def __init__(self, solver, mtype, data_type, factor_time):
        self._solver = solver
        self._mtype = mtype
        self._data_type = data_type
        self._is_complex = np.issubdtype(data_type, np.complexfloating)
        self._factor_time = factor_time
        self._solve_time = None
        self._info = None

    def solve(self, b, verbose=None):
        b = np.asarray(b)
        if b.dtype != self._data_type:
            # Pydiso wrapper would do the conversion and throw a warning;
            # hence, doing data type conversion in advance
            b = b.astype(self._data_type)

        _solve_start = time.time()
        x = self._solver.solve(b)
        self._solve_time = time.time() - _solve_start
        return x

    def info(self):
        iparm = self._solver.iparm
        return {'FactorTime': self._factor_time,
                'SolveTime': self._solve_time,
                'Factormem': round(iparm[15]/1024, 4),
                'Solvemem': round(iparm[16]/1024, 4),
                'IterRefine': iparm[6]}

    def delete(self):
        # Preserve the info before memory deallocation for solver
        self._info = self.info()
        self._solver = None


_MATRIX_TYPE_NAMES = {
    4: 'Complex Hermitian positive-definite',
    -4: 'Complex Hermitian indefinite',
    2: 'Real symmetric positive-definite',
    -2: 'Real symmetric indefinite',
    11: 'Real non-symmetric',
    13: 'Complex non-symmetric',
}


def _mkl_matrix_type(dtype, solver_args):
    is_complex = np.issubdtype(dtype, np.complexfloating)
    if not solver_args['hermitian']:
        return 13 if is_complex else 11
    out = 4 if is_complex else 2
    return out if solver_args['posdef'] else -out

# Returns factorisation object: important for tests
def mkl_splu(A, perm=None, verbose=False, **kwargs):
    """
    Returns the LU factorization of the sparse matrix A.

    Parameters
    ----------
    A : csr_matrix
        Sparse input matrix.
    perm : ndarray (optional)
        User defined matrix factorization permutation.
    verbose : bool {False, True}
        Report factorization details.

    Returns
    -------
    lu : mkl_lu
        Returns object containing LU factorization with a
        solve method for solving with a given RHS vector.

    """
    if not (sp.issparse(A) and A.format == "csr"):
        raise TypeError('Input matrix must be in sparse CSR format.')

    if A.shape[0] != A.shape[1]:
        raise Exception('Input matrix must be square')

    dim = A.shape[0]
    solver_args = _default_solver_args()
    left_over_args = set(kwargs) - set(solver_args)
    if left_over_args:
        raise ValueError(
            f"Unknown keyword arguments pass to mkl_splu: {left_over_args}"
        )
    solver_args.update(kwargs)

    # For backward compat, map values to pydiso.mkl_solver.MKLPardisoSolver's args
    wrapper_args = {}

    is_complex = bool(A.dtype == np.complex128) # TODO: this pydiso also does
    
    if not is_complex:
        A = sp.csr_matrix(A, dtype=np.float64, copy=False)
    data_type = A.dtype
    # Create pointer to internal memory
    pt = np.zeros(64, dtype=int)
    np_pt = pt.ctypes.data_as(ndpointer(int, ndim=1, flags='C'))

    # Create pointers to sparse matrix arrays # TODO: this will be handled by pydiso
    data = A.data.ctypes.data_as(ndpointer(data_type, ndim=1, flags='C'))
    indptr = A.indptr.ctypes.data_as(ndpointer(np.int32, ndim=1, flags='C'))
    indices = A.indices.ctypes.data_as(ndpointer(np.int32, ndim=1, flags='C'))

    # Setup perm array
    if perm is None:
        perm = np.zeros(dim, dtype=np.int32)
        has_perm = 0
    else:
        has_perm = 1
    np_perm = perm.ctypes.data_as(ndpointer(np.int32, ndim=1, flags='C'))

    # setup iparm
    # TODO: refactor it to setting arguments for MKLPardisoSolver
    # MKLPardisoSolver: use a public setter for iparm
    iparm = _pardiso_parameters(
        solver_args['hermitian'],
        has_perm,
        solver_args['max_iter_refine'],
        solver_args['scaling_vectors'],
        solver_args['weighted_matching'],
    )
    
    mtype = _mkl_matrix_type(data_type, solver_args) # TODO: wrapper also supports complex64/float64, we should adapt the matrix type inference
    
    # TODO: evaluate pydiso's logging capabilities: what is there and what we should add
    if verbose:
        print('Solver Initialization')
        print('---------------------')
        print('Input matrix type: ', _MATRIX_TYPE_NAMES[mtype])
        print('Input matrix shape:', A.shape)
        print('Input matrix NNZ:  ', A.nnz)
        print()

    # Call solver # TODO: here, we will call the solver
    _factor_start = time.time()
    solver = MKLPardisoSolver(A, matrix_type=mtype)
    # TODO: Check if the class handles same iparm's by default to avoid redundant set_iparm calls
    # TODO: we cannot set iparm before analysis and factorisation - the setter performs it after those steps;
    # we should find a way to pass 1/10/12/23 upon initialisation
    solver.set_iparm(7, solver_args['max_iter_refine'])
    _factor_time = time.time() - _factor_start
    # TODO: iparm must be taken from solve
    if verbose:
        print('Analysis and Factorization Stage')
        print('--------------------------------')
        print('Factorization time:       ', round(solver._factor_time, 4))
        print('Factorization memory (Mb):', round(solver._iparm[15]/1024, 4))
        print('NNZ in LU factors:        ', solver.iparm[17])
        print()
    return mkl_lu(solver, mtype, data_type, _factor_time)

